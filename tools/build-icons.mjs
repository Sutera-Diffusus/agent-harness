// Build vendor/icons.js: inline lucide UI icons + simple-icons brand SVGs.
// Run: node tools/build-icons.mjs
import fs from 'fs';

const LUCIDE = [
  'search', 'settings', 'plus', 'panel-left-close', 'panel-left-open',
  'activity', 'gauge', 'folders', 'folder-open', 'folder-git-2',
  'maximize-2', 'minimize-2', 'x', 'rotate-ccw', 'zap', 'git-branch',
  'clock', 'copy', 'archive-restore', 'chevron-right', 'chevron-down', 'radio-tower', 'layers', 'timer', 'scan',
  'square', 'columns-2', 'grid-2x2', 'layout-grid', 'circle-help', 'terminal',
];
const SIMPLE = ['deepseek', 'kimi', 'opencode', 'gnubash'];

const lucideDir = 'node_modules/lucide-static/icons';
const simpleDir = 'node_modules/simple-icons/icons';

function readLucide(name) {
  const p = `${lucideDir}/${name}.svg`;
  if (!fs.existsSync(p)) throw new Error('lucide missing: ' + name);
  let svg = fs.readFileSync(p, 'utf8').trim();
  svg = svg.replace(/^<svg/, '<svg class="lu"').replace(/width="24" height="24"/, '');
  return svg;
}
function readSimple(name) {
  const p = `${simpleDir}/${name}.svg`;
  if (!fs.existsSync(p)) throw new Error('simple-icons missing: ' + name);
  let svg = fs.readFileSync(p, 'utf8').trim();
  svg = svg.replace(/fill="#[0-9a-fA-F]{3,8}"/, 'fill="currentColor"');
  return svg;
}

const out = {lucide: {}, simple: {}};
for (const n of LUCIDE) out.lucide[n] = readLucide(n);
for (const n of SIMPLE) out.simple[n] = readSimple(n);

fs.writeFileSync('vendor/icons.js',
  '// generated by tools/build-icons.mjs — real icons from lucide-static + simple-icons\n' +
  'window.__ICONS = ' + JSON.stringify(out) + ';\n');
console.log('icons.js written:', Object.keys(out.lucide).length, 'lucide +', Object.keys(out.simple).length, 'simple');
